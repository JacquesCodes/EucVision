# Load the raw dataset
file_path = '/content/drive/My Drive/EucVision/01. Master Dataset.csv'
df = pd.read_csv(file_path, low_memory=False)

# Clean, simple numerical date parsing
df['Date'] = pd.to_datetime(df['Date'], format='%d-%m-%Y', errors='coerce')

# Ensure critical measurement columns are treated as numeric
numeric_cols = [
    'Crown_Area',
    'Tree_Height',
    'Stem_Diameter',
    'Ground_Truth_Height',
    'LiDAR_Height',
    'Spacing'
]

for col in numeric_cols:
    df[col] = pd.to_numeric(df[col], errors='coerce')

# Generate a unique identifier for each tree to track growth over time
df['Tree_ID'] = (df['Compartment'].astype(str) + '_' +
                 df['Line'].astype(str) + '_' +
                 df['Plot'].astype(str) + '_' +
                 df['Tree'].map('{:.2f}'.format))

# Collapse split rows before math calculations happen
group_cols = ['Date', 'Compartment', 'Line', 'Plot', 'Culture', 'Spacing', 'Species', 'Tree', 'Tree_ID']

if 'Death_Date' in df.columns:
    group_cols.append('Death_Date')

df = df.groupby(group_cols, dropna=False).first().reset_index()

# Sort chronologically by tree to prepare for sequential calculations
df = df.sort_values(by=['Tree_ID', 'Date'])

# ------------------------------------------------------------------------------
# 2.5 MORTALITY FILTERING
# ------------------------------------------------------------------------------
if 'Death_Date' in df.columns:
    df['Parsed_Death_Date'] = pd.to_datetime(df['Death_Date'], format='%d-%m-%Y', errors='coerce')
    df['Is_Dead'] = df['Parsed_Death_Date'].notna() & (df['Date'] >= df['Parsed_Death_Date'])

    metrics_to_wipe = ['Crown_Area', 'Tree_Height', 'Stem_Diameter', 'Ground_Truth_Height', 'LiDAR_Height']
    df.loc[df['Is_Dead'], metrics_to_wipe] = np.nan
    df = df.drop(columns=['Parsed_Death_Date', 'Is_Dead'])
    print("Mortality Filter Applied: Dead tree metrics successfully wiped.")

# ------------------------------------------------------------------------------
# 3. HEIGHT ADJUSTMENT PIPELINE (SPECIES ARCHITECTURE + EPOCHS)
# ------------------------------------------------------------------------------

# Store original raw height for reference
df['Original_Height'] = df['Tree_Height']

# Biological constraint validation on raw height
df = df.sort_values(by=['Tree_ID', 'Date'])
df['Tree_Height'] = df.groupby('Tree_ID')['Tree_Height'].cummax()

# 1. EXTRACT GROUND TRUTHS
target_date_tls = pd.to_datetime('2025-11-28')
target_date_field = pd.to_datetime('2026-03-23')
target_date_als = pd.to_datetime('2026-06-26')
cutoff_date = pd.to_datetime('2026-03-16')   # TLS -> Field model switch
cutoff_date_als = target_date_als             # Field -> ALS model switch

tls_ref = df[df['Date'] == target_date_tls][['Tree_ID', 'LiDAR_Height']].rename(columns={'LiDAR_Height': 'Target_Height'})
field_ref = df[df['Date'] == target_date_field][['Tree_ID', 'Ground_Truth_Height']].rename(columns={'Ground_Truth_Height': 'Target_Height'})
als_field_ref = df[df['Date'] == target_date_als][['Tree_ID', 'Ground_Truth_Height']].rename(columns={'Ground_Truth_Height': 'Target_Height'})

df['Target_Height'] = np.nan

mask_tls = df['Date'] == target_date_tls
df.loc[mask_tls, 'Target_Height'] = df.loc[mask_tls, 'Tree_ID'].map(tls_ref.set_index('Tree_ID')['Target_Height'])

mask_field = df['Date'] == target_date_field
df.loc[mask_field, 'Target_Height'] = df.loc[mask_field, 'Tree_ID'].map(field_ref.set_index('Tree_ID')['Target_Height'])

mask_als = df['Date'] == target_date_als
df.loc[mask_als, 'Target_Height'] = df.loc[mask_als, 'Tree_ID'].map(als_field_ref.set_index('Tree_ID')['Target_Height'])
# 2. TRAIN CALIBRATION MODELS (Per Species, Per Epoch)
calibration_models = []

for target_date in [target_date_tls, target_date_field, target_date_als]:
    date_data = df[df['Date'] == target_date].dropna(subset=['Target_Height', 'Tree_Height', 'Species'])

    for species, group in date_data.groupby('Species'):
        if len(group) > 5:  # Minimum N to fit a stable line
            X = group[['Tree_Height']]
            y = group['Target_Height']
            reg = LinearRegression().fit(X, y)

            calibration_models.append({
                'Epoch_Date': target_date,
                'Species': species,
                'Slope': reg.coef_[0],
                'Intercept': reg.intercept_
            })
        else:
            # Fallback for insufficient species data: apply simple mean offset
            mean_diff = (group['Target_Height'] - group['Tree_Height']).mean() if len(group) > 0 else 0
            calibration_models.append({
                'Epoch_Date': target_date,
                'Species': species,
                'Slope': 1.0,
                'Intercept': mean_diff
            })

model_df = pd.DataFrame(calibration_models)

# 3. APPLY THE PREDICTIVE MODELS
df['Calibrated_Height'] = df['Tree_Height']

# Only apply UAV calibration to flights on or after Sept 1, 2025
uav_start_date = pd.to_datetime('2025-09-01')
is_uav = df['Date'] >= uav_start_date
df_uav = df[is_uav].copy()

mask_before_switch = df_uav['Date'] < cutoff_date
mask_mid_switch = (df_uav['Date'] >= cutoff_date) & (df_uav['Date'] < cutoff_date_als)
mask_after_als = df_uav['Date'] >= cutoff_date_als

# Apply November models (TLS) to pre-switch drone data
nov_models = model_df[model_df['Epoch_Date'] == target_date_tls].set_index('Species')
for species in df_uav['Species'].unique():
    if species in nov_models.index:
        m = nov_models.loc[species, 'Slope']
        c = nov_models.loc[species, 'Intercept']
        spc_mask = mask_before_switch & (df_uav['Species'] == species)
        df_uav.loc[spc_mask, 'Calibrated_Height'] = (df_uav.loc[spc_mask, 'Tree_Height'] * m) + c

# Apply March models (Field) to mid-window drone data
mar_models = model_df[model_df['Epoch_Date'] == target_date_field].set_index('Species')
for species in df_uav['Species'].unique():
    if species in mar_models.index:
        m = mar_models.loc[species, 'Slope']
        c = mar_models.loc[species, 'Intercept']
        spc_mask = mask_mid_switch & (df_uav['Species'] == species)
        df_uav.loc[spc_mask, 'Calibrated_Height'] = (df_uav.loc[spc_mask, 'Tree_Height'] * m) + c

# Apply June (ALS) models to post-June-26 drone data
als_models = model_df[model_df['Epoch_Date'] == target_date_als].set_index('Species')
for species in df_uav['Species'].unique():
    if species in als_models.index:
        m = als_models.loc[species, 'Slope']
        c = als_models.loc[species, 'Intercept']
        spc_mask = mask_after_als & (df_uav['Species'] == species)
        df_uav.loc[spc_mask, 'Calibrated_Height'] = (df_uav.loc[spc_mask, 'Tree_Height'] * m) + c

# Re-integrate and validate
df.loc[is_uav, 'Calibrated_Height'] = df_uav['Calibrated_Height']

# Final biological constraint validation to ensure no shrinking over time
df = df.sort_values(by=['Tree_ID', 'Date'])
df['Calibrated_Height'] = df.groupby('Tree_ID')['Calibrated_Height'].cummax()

# ------------------------------------------------------------------------------
# 3.5 STATISTICAL VALIDATION (K-FOLD OUT-OF-SAMPLE PREDICTIONS)
# ------------------------------------------------------------------------------
df['Honest_Calibrated_Height'] = df['Calibrated_Height']

for cal_date in [target_date_tls, target_date_field, target_date_als]:
    df_temp = df[df['Date'] == cal_date].copy()
    mask = df_temp['Target_Height'].notna() & df_temp['Tree_Height'].notna() & df_temp['Species'].notna()

    if mask.sum() > 20:
        # Create a dynamic matrix that mimics independent per-species regressions
        # by including Tree_Height, Species dummies, and their interaction terms
        X = pd.get_dummies(df_temp.loc[mask, ['Tree_Height', 'Species']], drop_first=True, dtype=float)

        interaction_cols = {}
        for col in X.columns:
            if col.startswith('Species_'):
                interaction_cols[f'Height_x_{col}'] = X['Tree_Height'] * X[col]
        X = pd.concat([X, pd.DataFrame(interaction_cols)], axis=1)

        y = df_temp.loc[mask, 'Target_Height']

        # 5-Fold cross-validation predicting actual target height directly
        cv = KFold(n_splits=5, shuffle=True, random_state=42)
        oos_preds = cross_val_predict(LinearRegression(), X, y, cv=cv)

        valid_indices = df_temp.loc[mask].index
        df.loc[valid_indices, 'Honest_Calibrated_Height'] = oos_preds

# Cleanup
df = df.drop(columns=['Target_Height'])

# ------------------------------------------------------------------------------
# 4. FORESTRY METRIC DERIVATION
# ------------------------------------------------------------------------------
df = df.sort_values('Date')

df['Crown_Diameter'] = 2 * np.sqrt(df['Crown_Area'] / np.pi)
df['Stem_Diameter'] = df['Stem_Diameter'] / 10
df['Basal_Area'] = np.pi * (df['Stem_Diameter'] / 2) ** 2

# ------------------------------------------------------------------------------
