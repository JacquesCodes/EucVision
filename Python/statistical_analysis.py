# ── 4. LMM formula builder ────────────────────────────────────────────────────
def build_formula(response):
    return f"{response} ~ Months * C(Species) + C(Spacing)"

def fit_lmm(data, response, label):
    print(f"\n  Fitting {label}...")
    formula = build_formula(response)
    try:
        model = smf.mixedlm(
            formula,
            data=data.dropna(subset=[response]),
            groups=data.dropna(subset=[response])["Plot_ID"],
            re_formula="~Months"
        )
        result = model.fit(reml=True, method="lbfgs", maxiter=200)
        print(f"    Converged: {result.converged} | "
              f"Log-lik: {result.llf:.1f} | "
              f"N obs: {result.nobs:,}")
        return result
    except Exception as e:
        print(f"    ERROR: {e}")
        return None

