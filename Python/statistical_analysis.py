    qmd_cm = np.sqrt((group['Stem_Diameter'] ** 2).mean())
    rd = stems_per_ha * CURTIS_K * (qmd_cm ** 1.5)
    density_rows.append({'Spacing': float(spacing), 'Species': 'Mixed', 'Plot': plot, 'RD': rd})

