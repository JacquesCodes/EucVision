def gini_coefficient(values):
    """
    Compute the Gini coefficient for an array of non-negative values.
    Returns NaN if fewer than 2 valid values.
    """
    arr = np.array(values, dtype=float)
    arr = arr[~np.isnan(arr) & (arr >= 0)]
    n = len(arr)
    if n < 2:
        return np.nan
    arr = np.sort(arr)
    # Standard formula: G = (2 * sum(i * x_i)) / (n * sum(x_i)) - (n+1)/n
    idx = np.arange(1, n + 1)
    return (2 * np.sum(idx * arr) / (n * np.sum(arr))) - (n + 1) / n


def compute_gini_timeseries(df_source, metric_col):
    """
    Compute per-date Gini coefficient across the WHOLE population
    for each (Spacing, Species/Mixed) group.
    Returns a dict keyed by spacing, each value a dict keyed by species
    containing a DataFrame with columns [Date, Gini].
    """
    df_clean = df_source.dropna(subset=[metric_col, 'Spacing', 'Date', 'Culture']).copy()
    result = {}

    spacings = sorted(df_clean['Spacing'].unique())
    for spacing in spacings:
        result[spacing] = {}
        sp_data = df_clean[df_clean['Spacing'] == spacing]

        # Pure stands — per species
        pure = sp_data[sp_data['Culture'] == 'Single']
        for species, grp in pure.groupby('Species'):
            ts = (grp.groupby('Date')[metric_col]
                     .apply(gini_coefficient)
                     .reset_index()
                     .rename(columns={metric_col: 'Gini'}))
            result[spacing][species] = ts

        # Mixed stands — all trees in mixed plots together
        mixed = sp_data[sp_data['Culture'] == 'Mix']
        if not mixed.empty:
            ts = (mixed.groupby('Date')[metric_col]
                       .apply(gini_coefficient)
                       .reset_index()
                       .rename(columns={metric_col: 'Gini'}))
            result[spacing]['Mixed'] = ts

    return result

