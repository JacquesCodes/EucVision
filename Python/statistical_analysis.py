def extract_summary(result, model_label, response_label, log_scale=False):
    if result is None:
        return pd.DataFrame()

    params = result.params
    bse    = result.bse
    pvals  = result.pvalues
    ci     = result.conf_int()

    rows = []
    for term in params.index:
        if term in ["Group Var", "Group x Months Cov", "Months Var"]:
            continue
        row = {
            "Model":     model_label,
            "Response":  response_label,
            "Term":      term,
            "Coef":      round(params[term], 4),
            "SE":        round(bse[term], 4),
            "CI_lower":  round(ci.loc[term, 0], 4),
            "CI_upper":  round(ci.loc[term, 1], 4),
            "p_value":   round(pvals[term], 4),
            "Sig":       ("***" if pvals[term] < 0.001 else
                          "**"  if pvals[term] < 0.01  else
                          "*"   if pvals[term] < 0.05  else
                          "."   if pvals[term] < 0.10  else "ns"),
        }
        if log_scale:
            row["exp_coef"] = round(np.exp(params[term]), 4)
        rows.append(row)

    return pd.DataFrame(rows)

